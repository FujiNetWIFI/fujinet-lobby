#!/usr/bin/env bash
# build.sh -- assemble the Arcadia 2001 Game Lobby.
#
# Output: build/lobby.bin, always exactly 8192 bytes: image 0x0000-0x0FFF
# is CPU $0000-$0FFF (block 1), image 0x1000-0x1FFF is CPU $2000-$2FFF
# (block 2). The assembler works in CPU addresses; p2bin emits a
# $0000-$2FFF flat and tools/mkimage.py folds it, rejecting anything in
# the $1000-$1FFF console-RAM hole or the $2B00+ mailbox pages. "FUJI" is
# stamped at image 0x1CFC (without the claim the mailbox goes dead once
# a booted image runs), then checkrom.py enforces the layout,
# checkdepth.py bounds the call graph to the 2650's 8-entry return
# stack, and checksize.py prints per-module budgets.
#
# Env:
#   ENDPOINT=...   the lobby's /view URL
#                  (default https://lobby.fujinet.online/view)
#   PLATFORM=...   the platform tag rooms are listed for (default arcadia)

set -euo pipefail
cd "$(dirname "$0")"

CLAIM_OFF=$((0x1CFC))

if command -v asl >/dev/null 2>&1; then
    AS=asl P2BIN=p2bin
elif [ -x "$HOME/asl/asl" ]; then
    AS="$HOME/asl/asl" P2BIN="$HOME/asl/p2bin"
else
    echo "build.sh: Macroassembler AS (asl, p2bin) not found" >&2
    exit 1
fi

mkdir -p build

# Regenerated every run so a stale value cannot survive an env change.
{
    echo "; generated by build.sh -- do not edit"
    printf 'UENDPT: DB      "%s",0\n' "${ENDPOINT:-https://lobby.fujinet.online/view}"
    printf 'UPLAT:  DB      "%s",0\n' "${PLATFORM:-arcadia}"
} > build/endpoint.inc

$AS -q -L lobby.asm -o build/lobby.p -olist build/lobby.lst
$P2BIN build/lobby.p build/lobby.flat -r '$0000-$2FFF' -l 0
python3 tools/mkimage.py build/lobby.flat build/lobby.bin
printf 'FUJI' | dd of=build/lobby.bin bs=1 seek=$CLAIM_OFF conv=notrunc status=none
rm -f build/lobby.p build/lobby.flat
python3 tools/checkrom.py build/lobby.bin
python3 tools/checkdepth.py --flow lobby.asm ./*.inc
python3 tools/checksize.py build/lobby.lst
echo "build/lobby.bin ok"
