#!/usr/bin/env python3
"""mkfont78.py -- the 7800 lobby's MARIA 320D font from CONFIG's font.txt.

font.txt is the format tools/mkfont.py reads (src/atari5200/font.txt is
CONFIG's character set). 320D is one bit a pixel, eight pixels a byte, and
the lobby reads its map with one-byte characters, so the font is 8 pages of
256 bytes: page k holds pixel row 7-k of every glyph (MARIA counts a zone's
OFFSET down from 7), and a glyph's code is its ASCII code. Every plane's ink
is a set bit; codes without a glyph are blank.

    mkfont78.py font.txt out.s
"""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from mkfont import parse  # noqa: E402


def main():
    tiles = parse(sys.argv[1])
    with open(sys.argv[2], "w") as out:
        out.write("; GENERATED by tools/mkfont78.py from %s -- do not edit.\n"
                  % os.path.basename(sys.argv[1]))
        out.write("; 8 pages: page k is pixel row 7-k of each glyph; code = ASCII.\n\n")
        out.write("        .export _a78_font\n")
        out.write('        .segment "TILES"\n')
        out.write("_a78_font:\n")
        for page in range(8):
            row = 7 - page
            out.write("; pixel row %d\n" % row)
            for base in range(0, 256, 16):
                vals = [tiles.get(c, [0] * 8)[row] if c < 128 else 0
                        for c in range(base, base + 16)]
                out.write("        .byte " + ",".join("$%02X" % v for v in vals) + "\n")


if __name__ == "__main__":
    main()
