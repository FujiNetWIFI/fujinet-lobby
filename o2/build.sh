#!/bin/bash
# build.sh -- the Odyssey 2 lobby: build/lobby.bin, a protocol 2 (APPBANK)
# image -- the fixed half ($400-$7FF) and NPAGES pages of 2K.
#
#   ./build.sh                          the image
#   ENDPOINT=... PLATFORM=...           the lobby server's /view, the tag
#                                       (https://lobby.fujinet.online/view, o2)
#   PADN= LEAD= Y_ROW0= X_ROWTXT=       the layout and timing (src/equ.inc)
#
# Needs Macroassembler AS (~/asl/asl and p2bin, or ASL=/P2BIN=).
set -e
HERE="$(cd "$(dirname "$0")" && pwd)"
OUT="${OUT:-$HERE/build}"
ASL="${ASL:-$HOME/asl/asl}"
P2BIN="${P2BIN:-$HOME/asl/p2bin}"
ENDPOINT="${ENDPOINT:-https://lobby.fujinet.online/view}"
PLATFORM="${PLATFORM:-o2}"
NPAGES=10
mkdir -p "$OUT"

python3 "$HERE/tools/checkflags.py" "$HERE"/src/*.inc
python3 "$HERE/tools/mkcharmap.py" "$OUT/charmap.inc"
python3 "$HERE/tools/mkglyphs.py" "$OUT/glyphs.inc"
{
  echo "; GENERATED by build.sh -- do not edit."
  printf 'u_base: db "N:%s?bin=1&platform=%s&pagesize=",0\n' "$ENDPOINT" "$PLATFORM"
} > "$OUT/endpoint.inc"
{
  echo "; GENERATED by build.sh -- do not edit."
  for v in PADN GRIDNOPP LEAD Y_ROW0 Y_T0 Y_T1 X_ROWTXT GRIDNOP; do
    [ -n "${!v:-}" ] && echo "$v equ ${!v}"
  done
  true
} > "$OUT/flags.inc"
cp "$HERE"/src/*.inc "$HERE/g7000.h" "$HERE/lobby.a48" "$OUT/"

parts=""
for p in $(seq 0 $((NPAGES-1))); do
  printf '; GENERATED by build.sh -- do not edit.\nPAGE equ %d\nNPAGES equ %d\n    include "lobby.a48"\n' \
    "$p" "$NPAGES" > "$OUT/lobby_p$p.a48"
  ( cd "$OUT" && "$ASL" -q -L -U "lobby_p$p.a48" \
      && "$P2BIN" "lobby_p$p.p" "lobby_pg$p.bin" -r 0x800-0xFFF -l 0 >/dev/null \
      && "$P2BIN" "lobby_p$p.p" "lobby_fx$p.bin" -r 0x400-0x7FF -l 0 >/dev/null )
  python3 "$HERE/tools/checkobj.py" "$OUT/lobby_p$p.p"
  python3 "$HERE/tools/checklayout.py" "$OUT/lobby_p$p.lst"
  python3 "$HERE/tools/checkmb.py" "$OUT/lobby_p$p.lst" >/dev/null
  python3 "$HERE/tools/checkpage.py" "$OUT/lobby_p$p.lst"
  # Every page carries the fixed half; they have to be the same bytes.
  cmp -s "$OUT/lobby_fx0.bin" "$OUT/lobby_fx$p.bin" \
    || { echo "build.sh: page $p assembled a different fixed half" >&2; exit 1; }
  parts="$parts $OUT/lobby_pg$p.bin"
done
# The stack is 8 levels and wraps silently: interrupts plus the deepest main
# chain have to fit. Every page's entries are counted from 0: they are
# entered by far_go, a jump. Only the libraries (pages 1 and 8) are
# farcalled; the screens hand over by far_go.
python3 "$HERE/tools/checkstack.py" --far 1,8 $(for p in $(seq 0 $((NPAGES-1))); do echo "$OUT/lobby_p$p.lst"; done) >/dev/null
cat "$OUT/lobby_fx0.bin" $parts > "$OUT/lobby.bin"
size=$(wc -c < "$OUT/lobby.bin")
[ "$size" -eq $((1024 + 2048 * NPAGES)) ] \
  || { echo "build.sh: lobby.bin is $size bytes" >&2; exit 1; }
echo "${OUT#$HERE/}/lobby.bin: $size bytes, $NPAGES pages"
